"""Compile the modern jersey numbers page (beta 81, owner nfl2k5_modern_numbers). Development requires GNU as/ld, gcc
and pyelftools; no game input.

entry.S and numbers.c are linked into one relocatable .text at page offset 0; the tables (tables.h) are rendered from
the owner module's constants (mod_editor/core/nfl2k5_modern_numbers.py: LEGAL_DECADES, GROUP_OF, WEIGHTS, SINGLE_DIGIT,
THRESHOLDS, DRAFT_CALLERS) into the build folder, so the Python rule and the page read the same numbers. Relocations
to the page itself are family "page"; absolute game addresses (calls and jumps into the retail code) are "stock".
`--check` reproduces the checked-in module mod_editor/core/nfl2k5_modern_numbers_code.py.
"""
from __future__ import annotations

import argparse
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from elftools.elf.elffile import ELFFile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TARGET = ROOT / "mod_editor/core/nfl2k5_modern_numbers_code.py"
DIVIDER = "# Generated from tools/modern_numbers by build.py.\n"
GCC_FLAGS = ("-m32 -march=i386 -Os -fomit-frame-pointer -fno-builtin -fno-stack-protector -ffreestanding -fno-pic "
             "-fno-pie -fno-asynchronous-unwind-tables -fno-jump-tables -Wall -Wextra -Werror").split()
PAGE_SIZE = 0x1000
CODE_LIMIT = 0xF00
EXPORTED = ("number_entry", "number_pick")


def _rule():
    sys.path.insert(0, str(ROOT))
    from mod_editor.core import nfl2k5_modern_numbers as mn
    return mn


def tables_h() -> str:
    mn = _rule()
    rows = lambda table: ", ".join("{" + ", ".join(str(v) for v in row) + "}" for row in table)  # noqa: E731
    return "\n".join([
        "/* Generated by tools/modern_numbers/build.py from mod_editor/core/nfl2k5_modern_numbers.py. Do not edit. */",
        "#define DRAFT_CALLERS %d" % len(mn.DRAFT_CALLERS),
        "static const unsigned short legal_decades[17] = {%s};" % ", ".join("0x%03x" % v for v in mn.LEGAL_DECADES),
        "static const unsigned char group_of[17] = {%s};" % ", ".join(str(v) for v in mn.GROUP_OF),
        "static const unsigned short weight[%d][10] = {%s};" % (len(mn.WEIGHTS), rows(mn.WEIGHTS)),
        "static const unsigned char single_digit[%d][5] = {%s};" % (len(mn.SINGLE_DIGIT), rows(mn.SINGLE_DIGIT)),
        "static const unsigned char thresholds[17][3] = {%s};" % rows(mn.THRESHOLDS),
        "static const unsigned int draft_callers[%d] = {%s};" % (len(mn.DRAFT_CALLERS),
                                                                 ", ".join("0x%08xu" % v for v in mn.DRAFT_CALLERS)),
        "#define SKILL 0x%xu" % mn.SKILL,
        "static const unsigned char retired[32][13] = {%s};" % rows(mn.RETIRED),
        "#define EXCEPTIONS %d" % len(mn.RETIRED_EXCEPTIONS),
        "static const unsigned char exceptions[%d][2] = {%s};" % (max(1, len(mn.RETIRED_EXCEPTIONS)),
                                                                  rows(mn.RETIRED_EXCEPTIONS) or "{255, 255}"),
        "#define LEGACY %d" % len(mn.LEGACY),
        "static const unsigned char legacy[%d][3] = {%s};" % (max(1, len(mn.LEGACY)), rows(mn.LEGACY) or "{255, 255, 255}"),
        ""])


def compile_page(temp):
    entry, logic, obj, script = (temp / name for name in ("entry.o", "numbers.o", "page.o", "page.ld"))
    (temp / "tables.h").write_text(tables_h(), encoding="utf-8")
    script.write_text("SECTIONS { .text 0 : { *entry.o(.text) *numbers.o(.text) *(.rodata*) *(.data*) *(COMMON) "
                      "*(.bss*) modern_numbers_end = .; } /DISCARD/ : { *(.comment*) *(.note*) *(.eh_frame*) *(.got*) } }")
    subprocess.run(["as", "--32", "-o", entry, HERE / "entry.S"], check=True)
    subprocess.run(["gcc", *GCC_FLAGS, "-I", str(temp), "-c", HERE / "numbers.c", "-o", logic], check=True)
    with logic.open("rb") as stream:
        elf = ELFFile(stream)
        for name in (".data", ".bss"):
            section = elf.get_section_by_name(name)
            if section is not None and section.data_size:
                raise ValueError(f"numbers.c must keep no writable data in the page ({name})")
    subprocess.run(["ld", "-r", "-m", "elf_i386", "-T", script, "-o", obj, entry, logic], check=True)
    return obj


def collect(temp):
    body = bytearray(b"\xcc" * CODE_LIMIT + bytes(PAGE_SIZE - CODE_LIMIT))
    labels, relocations = {}, []
    with compile_page(temp).open("rb") as stream:
        elf = ELFFile(stream)
        text = elf.get_section_by_name(".text")
        index = elf.get_section_index(".text")
        stray = [sec.name for sec in elf.iter_sections() if sec["sh_flags"] & 2 and sec.name != ".text" and sec.data_size]
        if stray:
            raise ValueError(f"code or data outside the page's .text: {stray}")
        data = text.data()
        syms = elf.get_section_by_name(".symtab")
        end = next(s["st_value"] for s in syms.iter_symbols() if s.name == "modern_numbers_end")
        if end > CODE_LIMIT or len(data) != end:
            raise ValueError("the modern numbers code does not fit below page + 0xF00")
        body[:end] = data
        for symbol in syms.iter_symbols():
            if symbol.name and symbol["st_shndx"] == index and symbol["st_info"]["type"] in ("STT_FUNC", "STT_NOTYPE"):
                labels[symbol.name] = symbol["st_value"]
        rel = elf.get_section_by_name(".rel.text")
        for fixup in rel.iter_relocations() if rel else ():
            field = fixup["r_offset"]
            if field + 4 > end:
                raise ValueError(f"relocation outside the code at {field:#x}")
            symbol = syms.get_symbol(fixup["r_info_sym"])
            section, value = symbol["st_shndx"], symbol["st_value"]
            addend = struct.unpack_from("<i", data, field)[0] + value
            if section == index:
                family = "page"
            elif section in ("SHN_UNDEF", "SHN_ABS") and not symbol.name:
                family = "stock"
            else:
                raise ValueError(f"Unsupported relocation to {symbol.name or section}")
            kind = fixup["r_info_type"]
            if kind not in (1, 2):
                raise ValueError(f"Unsupported i386 relocation {kind}")
            relocations.append((field, kind == 2, family, addend & 0xFFFFFFFF))
    return body, end, sorted(relocations), {name: labels[name] for name in EXPORTED}


def render():
    with tempfile.TemporaryDirectory(prefix="2k5-modern-numbers-") as folder:
        raw, code_bytes, fixes, labels = collect(Path(folder))
    lines = [DIVIDER.rstrip(), f"CODE_BYTES = {code_bytes:#x}", "", "_TEMPLATE = b''.join(("]
    pos = 0

    def literal(chunk):
        for start in range(0, len(chunk), 40):
            lines.append(f"    bytes.fromhex('{chunk[start:start + 40].hex()}'),")

    for match in re.finditer(rb"\x00{12,}|\xcc{12,}", bytes(raw)):
        literal(raw[pos:match.start()])
        length = match.end() - match.start()
        lines.append(f"    bytes({length})," if raw[match.start()] == 0 else f"    b'\\xcc' * {length},")
        pos = match.end()
    literal(raw[pos:])
    lines += ["))", "", "# (field offset, PC-relative, address family, offset including ELF addend)", "_RELOCATIONS = ("]
    for offset, relative, family, value in fixes:
        lines.append(f"    ({offset:#06x}, {relative}, {family!r}, {value:#x}),")
    lines += [")", "", "LABELS = {"]
    lines.extend(f"    {name!r}: {offset:#x}," for name, offset in sorted(labels.items()))
    return "\n".join([*lines, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    old = TARGET.read_text(encoding="utf-8")
    prefix, marker, _ = old.partition(DIVIDER)
    if not marker:
        raise ValueError("Missing generated table marker")
    new = prefix + render()
    if args.check:
        if old != new:
            raise SystemExit("The modern numbers native template is stale")
    else:
        TARGET.write_text(new, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
