"""Reproduce the b780 scramble blocking byte template with GNU as; development use only.

EXPERIMENTAL. One owner, ``nfl2k5_scramble_blocking`` (receivers and backs block for a quarterback who runs past
the line). The ELF32 reader is the one in ``tools/nfl2k5_rules_assemble.py``; no compiler or ELF package is a runtime
dependency, and the tests read the committed template, never GNU as.
"""
from __future__ import annotations

from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from nfl2k5_rules_assemble import generate  # noqa: E402

OWNER = "nfl2k5_scramble_blocking"


def template() -> str:
    text = generate(OWNER)
    return text.replace("Generated by tools/nfl2k5_rules_assemble.py. EXPERIMENTAL / UNWITNESSED.",
                        "Generated by tools/nfl2k5_scramble_blocking_assemble.py. EXPERIMENTAL.", 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / f"mod_editor/core/{OWNER}_code.py"
    result = template()
    if args.check:
        if target.read_text(encoding="utf-8") != result:
            raise SystemExit(f"{OWNER} byte template is stale")
    else:
        target.write_bytes(result.encode("utf-8"))
    print(f"{OWNER} template verified" if args.check else f"{OWNER} template generated")


if __name__ == "__main__":
    main()
