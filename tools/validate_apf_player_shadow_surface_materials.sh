assert len(vertices) == 351
normal_values = []
uv_values = []
for index, row in enumerate(vertices):
    assert int(row["vertex"]) == index
    normal_raw = tuple(map(int, row["normal_raw_i16"].split(",")))
    tangent_raw = tuple(map(int, row["tangent_raw_i16"].split(",")))
    normal = tuple(snorm16(value) for value in normal_raw)
    tangent = tuple(snorm16(value) for value in tangent_raw)
    uv = (f32(2.0 * normal[3]), f32(2.0 * tangent[3]))
    exported_normal = tuple(float(row[name]) for name in ("normal_x", "normal_y", "normal_z"))
    exported_uv = (float(row["uv_u"]), float(row["uv_v"]))
    assert exported_normal == normal[:3]
    assert exported_uv == uv
    assert abs(math.sqrt(sum(value * value for value in normal[:3])) - 1.0) < 0.001
    assert abs(math.sqrt(sum(value * value for value in tangent[:3])) - 1.0) < 0.001
    normal_values.append(exported_normal)
    uv_values.append(exported_uv)
assert len(set(uv_values)) == 278
assert min(value[0] for value in uv_values) == 0.06280709058046341
