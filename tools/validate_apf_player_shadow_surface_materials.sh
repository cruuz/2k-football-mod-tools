#!/usr/bin/env bash
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"

report=reports/assets/apf_player_shadow_surface_materials.json
vertices=reports/assets/apf_player_shadow_surface_vertices.tsv
samplers=reports/assets/apf_player_shadow_shader_samplers.tsv
links=reports/assets/apf_player_shadow_static_texture_links.tsv
trace=reports/assets/apf_player_shadow_surface_material_ghidra/player_shadow_surface_material_trace.txt
pseudo=reports/assets/apf_player_shadow_surface_material_ghidra/player_shadow_surface_material_pseudo_c.c
gltf=assets/intermediate/apf2k8/skinned/1310_0415_player_shadow_surface.gltf
bin=assets/intermediate/apf2k8/skinned/1310_0415_player_shadow_surface.bin
canonical_gltf=assets/intermediate/apf2k8/skinned/1310_0415_player_shadow_skin.gltf
canonical_bin=assets/intermediate/apf2k8/skinned/1310_0415_player_shadow_skin.bin
doc=docs/research/apf_player_shadow_surface_materials.md

for required in \
  "$report" "$vertices" "$samplers" "$links" "$trace" "$pseudo" \
  "$gltf" "$bin" "$canonical_gltf" "$canonical_bin" "$doc" \
  tools/apf_player_shadow_surface_materials.py \
  tools/apf_player_shadow_surface_assimp_validate.cpp \
  tools/ghidra_scripts/apf/ApfPlayerShadowSurfaceMaterialTrace.java \
  tools/apf_outer.py tools/apf_inner.py \
  extracted/'All-Pro Football 2K8 (USA)'/0A \
  extracted/'All-Pro Football 2K8 (USA)'/default.xex \
  reports/assets/apf_scene_inventory.json; do
  test -f "$required"
done

python3 -m py_compile tools/apf_player_shadow_surface_materials.py
bash -n "$0"
pkg-config --exists assimp

temporary=$(mktemp -d /tmp/apf-player-shadow-surface.XXXXXX)
trap 'rm -rf "$temporary"' EXIT

build_assimp_validator() {
  local cxx=$1
  local label=$2
  "$cxx" -std=c++20 -O2 -Wall -Wextra \
    tools/apf_player_shadow_surface_assimp_validate.cpp \
    $(pkg-config --cflags --libs assimp) \
    -o "$temporary/assimp-$label"
  "$temporary/assimp-$label" "$gltf"
}

build_assimp_validator c++ gcc
compiler_count=1
if command -v clang++-18 >/dev/null 2>&1; then
  build_assimp_validator clang++-18 clang
  compiler_count=2
fi

generate() {
  local seed=$1
  PYTHONHASHSEED=$seed python3 tools/apf_player_shadow_surface_materials.py
}

# Use the published destinations for both seeds so provenance paths in the
# report are identical, then compare every generated byte.
generate 1
cp "$report" "$temporary/report-one.json"
cp "$vertices" "$temporary/vertices-one.tsv"
cp "$samplers" "$temporary/samplers-one.tsv"
cp "$links" "$temporary/links-one.tsv"
cp "$gltf" "$temporary/surface-one.gltf"
cp "$bin" "$temporary/surface-one.bin"
generate 777
cmp "$temporary/report-one.json" "$report"
cmp "$temporary/vertices-one.tsv" "$vertices"
cmp "$temporary/samplers-one.tsv" "$samplers"
cmp "$temporary/links-one.tsv" "$links"
cmp "$temporary/surface-one.gltf" "$gltf"
cmp "$temporary/surface-one.bin" "$bin"

python3 - "$report" "$vertices" "$samplers" "$links" "$trace" "$pseudo" \
  "$gltf" "$bin" "$canonical_bin" <<'PY'
import csv
import hashlib
import json
import math
from pathlib import Path
import struct
import sys

report_path, vertices_path, samplers_path, links_path, trace_path, pseudo_path, \
    gltf_path, bin_path, canonical_bin_path = map(Path, sys.argv[1:])
report = json.loads(report_path.read_text(encoding="utf-8"))
vertices = list(csv.DictReader(vertices_path.open(encoding="utf-8"), delimiter="\t"))
samplers = list(csv.DictReader(samplers_path.open(encoding="utf-8"), delimiter="\t"))
links = list(csv.DictReader(links_path.open(encoding="utf-8"), delimiter="\t"))
trace = trace_path.read_text(encoding="utf-8")
pseudo = pseudo_path.read_text(encoding="utf-8")
document = json.loads(gltf_path.read_text(encoding="utf-8"))
binary = bin_path.read_bytes()
canonical_binary = canonical_bin_path.read_bytes()

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]

def snorm16(value):
    return f32(max(value / 32767.0, -1.0))

assert report["schema"] == "apf_player_shadow_surface_materials/v1"
selection = report["selection"]
assert selection["outer_table_index"] == 1310
assert selection["outer_name"] == "global.iff"
assert selection["inner_file_index"] == 415
assert selection["inner_name"] == "player_shadow"
assert selection["inner_type"] == "SCNE"
assert selection["parts"] == [{
    "block": "DRAM", "block_index": 0, "length": 23424, "offset": 3633664,
}]
assert selection["has_vram_part"] is False
assert selection["system_sha256"] == \
    "2042ce844a84a3f4b311bd8554b81744555d3efd6f2e4b5cac6c28a2e0735819"

decision = report["decision"]
for key in (
    "exact_iff_ownership_proved",
    "normal_and_packed_uv_authoring_contract_proved_for_all_vertices",
    "shader_sampler_interface_and_dimensions_proved",
    "draw_to_runtime_material_indirection_proved",
    "separate_no_material_surface_gltf_emitted",
):
    assert decision[key] is True
for key in (
    "concrete_txtr_or_render_target_bindings_proved",
    "exact_sampler_filter_and_address_modes_proved",
    "mod_ready_png_and_gltf_material_safe_to_emit",
    "png_emitted",
    "gltf_material_emitted",
):
    assert decision[key] is False
assert len(report["portme"]) == 4
assert report["portme"][0].startswith("// PORTME before 0x84B27AD0")
assert report["portme"][1].startswith("// PORTME at 0x84B15488")
assert report["portme"][2].startswith("// PORTME at 0x84B14DA0 -> 0x84B28EA0")
assert report["portme"][3].startswith("// PORTME at 0x84AA4728")

shader = report["pixel_shader"]
assert shader["sha256"] == \
    "c7e1ed011010fef44591c7c477ac3c18582282cd2fe205dd9489b0b6c77ad383"
