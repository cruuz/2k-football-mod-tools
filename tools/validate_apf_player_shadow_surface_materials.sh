assert shader["xenosrecomp"]["generated_vertex_hlsl_sha256"] == \
    "8cd25351644ea47b9b2c274f386a7e8df41daf4bfd58a95851763d050175913e"
assert shader["xenosrecomp"]["generated_pixel_hlsl_sha256"] == \
    "89da3cf04a5061841b97659ece0ea74d51dd6eff90c994bbf5fe064b77c7e4fe"
expected_samplers = [
    ("BaseMap", "0", "sampler2D"),
    ("NormalMap", "1", "sampler2D"),
    ("GlossOcclusionMap", "2", "sampler2D"),
    ("GroundShadowSampler", "3", "sampler2D"),
    ("SpecularLightmapSampler", "4", "samplerCUBE"),
]
assert [(row["name"], row["register"], row["kind"]) for row in samplers] == \
    expected_samplers
assert all(row["concrete_resource"].startswith("PORTME") for row in samplers)

scan = report["static_file_id_scan"]
assert scan["aligned_u32_offsets_scanned"] == 5856
assert scan["global_iff_file_count"] == 442 and scan["txtr_matches"] == 0
assert [(row["system_offset"], row["value"], row["inner_file_index"],
         row["name"], row["type"], row["classification"]) for row in links] == [
    ("0x0164", "0xea7614f3", "415", "player_shadow", "SCNE", "self-reference"),
    ("0x0254", "0xea7614f3", "415", "player_shadow", "SCNE", "self-reference"),
    ("0x0274", "0xea7614f3", "415", "player_shadow", "SCNE", "self-reference"),
