#!/usr/bin/env python3
"""Regenerate the gadget-play runtime template (beta 81, Q62 redo) with GNU gcc/binutils; development use only.

The generated ``mod_editor/core/nfl2k5_gadget_play_code.py`` is checked in, so Studio users never need a compiler.
``--check`` fails when the checked-in template differs from a fresh build (gcc 13.3, binutils 2.42).

The sources (``lineup.S``, ``lookup.c``, ``speed.S``) are the runtime of Codex's private Q62 candidate
(job/b81-gadget-proof f9df9acc5, qualified as XBE 7963a1db on 20 CPU games, the attract game and a MyCareer game).
Beta 81 review F1 added ``restore.S`` and two stores of its marker (one in ``lineup.S``, one in ``speed.S``); the
classifier ``lookup.c`` is unchanged. The code always sits at the fixed gadget slot (``nfl2k5_xbe_space.GADGET_CODE_VA``). Five link-time
values change from build to build: the native gate (the target of the picker's gate call 0xE8864, which a later
owner may own) and four addresses inside the gadget table (its layout depends on the disc's play books). The
generator links the runtime once with template values and once more per value with only that value moved, and
records every 32-bit field that moved by exactly the same amount. Absolute and pc-relative fields both move by the
symbol's change, so the installer adds (new - template) to each recorded field. Any other difference refuses.
"""
from __future__ import annotations

from pathlib import Path
import argparse
import subprocess
import sys
import tempfile

SOURCE = Path(__file__).resolve().parent
ROOT = SOURCE.parents[1]
TARGET = ROOT / "mod_editor/core/nfl2k5_gadget_play_code.py"
CODE_VA = 0x151F680
TABLE_VA = CODE_VA + 2048
# Template values: the retail gate target and a plausible table layout. Only the moves matter.
TEMPLATE = {"native_gate": 0x000E8340, "book_rows": TABLE_VA, "links": TABLE_VA + 0x250,
            "blobs": TABLE_VA + 0xB00, "pair_info": TABLE_VA + 0x31FC}
SYMBOLS = tuple(TEMPLATE)
LABELS = ("scoped_builder", "scope_return", "tapped_ordinal", "select_slot", "assign_if_fast", "restore_after_store",
          "gadget_team")
MOVE = 0x1230
CFLAGS = ["-m32", "-Os", "-std=c99", "-ffreestanding", "-fno-pic", "-fno-pie", "-fno-stack-protector",
          "-fno-asynchronous-unwind-tables", "-fno-unwind-tables", "-mno-sse", "-mpreferred-stack-boundary=2",
          "-Wall", "-Wextra", "-Werror"]
HEADING = ("Generated by tools/gadget_play/build.py (gcc 13.3, binutils 2.42) from tools/gadget_play/lineup.S, "
           "lookup.c and speed.S.")


def _run(*args: str) -> str:
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def link(values: dict[str, int]) -> tuple[bytes, dict[str, int]]:
    """The runtime linked at CODE_VA with the given symbol values (Codex's candidate.assemble, unchanged)."""
    with tempfile.TemporaryDirectory(prefix="gadget-play-") as folder:
        obj = Path(folder)
        for name in ("lineup", "speed", "restore"):
            _run("as", "--32", "-o", str(obj / f"{name}.o"), str(SOURCE / f"{name}.S"))
        _run("gcc", *CFLAGS, "-c", str(SOURCE / "lookup.c"), "-o", str(obj / "lookup.o"))
        defs = [f"--defsym={k}={v:#x}" for k, v in values.items()]
        _run("ld", "-m", "elf_i386", "--build-id=none", "-e", "scoped_builder", f"-Ttext={CODE_VA:#x}", *defs,
             "-o", str(obj / "runtime.elf"), str(obj / "lineup.o"), str(obj / "lookup.o"), str(obj / "speed.o"),
             str(obj / "restore.o"))
        symbols = {}
        for row in _run("nm", "--defined-only", "-n", str(obj / "runtime.elf")).splitlines():
            address, _, name = row.split()
            symbols[name] = int(address, 16)
        _run("objcopy", "-O", "binary", "-j", ".text", str(obj / "runtime.elf"), str(obj / "code"))
        return (obj / "code").read_bytes(), symbols


def generate() -> str:
    base, symbols = link(TEMPLATE)
    sites: dict[str, list[int]] = {}
    for name in SYMBOLS:
        moved, _ = link({**TEMPLATE, name: TEMPLATE[name] + MOVE})
        if len(moved) != len(base):
            raise ValueError(f"moving {name} changed the code length")
        found, i = [], 0
        while i < len(base):
            if moved[i] == base[i]:
                i += 1
                continue
            old = int.from_bytes(base[i:i + 4], "little")
            new = int.from_bytes(moved[i:i + 4], "little")
            if i + 4 > len(base) or (new - old) & 0xFFFFFFFF != MOVE:
                raise ValueError(f"unexpected difference at +{i:#x} when moving {name}")
            found.append(i)
            i += 4
        if not found:
            raise ValueError(f"{name} is not referenced")
        sites[name] = found
    every = sorted(i for found in sites.values() for i in found)
    if len(every) != len(set(every)):
        raise ValueError("two symbols share a field")
    labels = {name: symbols[name] - CODE_VA for name in LABELS}
    lines = [f'"""{HEADING}"""', "", f"CODE_VA = {CODE_VA:#x}", "TEMPLATE = bytes.fromhex("]
    lines += ['    "' + base[i:i + 40].hex() + '"' for i in range(0, len(base), 40)]
    lines += [")", "TEMPLATE_VALUES = {"] + [f"    {k!r}: {v:#x}," for k, v in TEMPLATE.items()]
    lines += ["}", "SITES = {"] + [f"    {k!r}: {tuple(v)!r}," for k, v in sites.items()]
    lines += ["}", "LABELS = {"] + [f"    {k!r}: {v:#x}," for k, v in labels.items()]
    return "\n".join(lines + ["}", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit("the gadget-play runtime template is stale")
        print("gadget-play runtime template verified")
    else:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
        print("gadget-play runtime template generated")


if __name__ == "__main__":
    sys.exit(main())
