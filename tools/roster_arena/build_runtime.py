"""Rebuild the relocatable arena runtime with GNU gcc/binutils (development only)."""
from pathlib import Path
import argparse
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent
TARGET = ROOT / 'mod_editor/core/nfl2k5_roster_arena_code.py'
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from mod_editor.core import nfl2k5_roster_arena as arena  # noqa: E402  (b779 ag1: the one capacity layout)
# The save-path shims (runtime.S) admit the retail and beta-78 capacity saves and name their wrapper sizes;
# the capacity variant's ARENA_SIZE / BLOCK_OFFSET are the current capacity arena.
ASM_SYMBOLS = (
    ('LEGACY_CAPACITY_SAVE', arena.LEGACY_CAPACITY_SAVE_SIZE),
    ('LEGACY_CAPACITY_DECLARED', arena.save_declared(arena.LEGACY_CAPACITY_ARENA_SIZE)),
    ('RESERVE_DECLARED', arena.save_declared(arena.ARENA_SIZE)),
    ('RETAIL_DECLARED', arena.save_declared(arena.RETAIL_SIZE)),
    ('RETAIL_SAVE', arena.RETAIL_SAVE_SIZE),
)
CAPACITY_DEFINES = ('ARENA_CAPACITY=1', f'ARENA_SIZE={arena.CAPACITY_ARENA_SIZE:#x}U',
                    f'BLOCK_OFFSET={arena.CAPACITY_BLOCK_OFFSET:#x}U')


def _compile(defines=()):
    with tempfile.TemporaryDirectory(prefix='roster-arena-code-') as folder:
        d = Path(folder).resolve()
        subprocess.run(['gcc', '-m32', '-Oz', '-ffreestanding', '-fno-builtin', '-fno-pic', '-fno-pie',
                        '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-fno-unwind-tables',
                        '-mpreferred-stack-boundary=2', '-mno-sse', '-mno-mmx', '-Wall', '-Wextra', '-Werror',
                        *[f'-D{d}' for d in defines],
                        '-c', str(SOURCE / 'runtime.c'), '-o', str(d / 'c.o')], check=True)
        subprocess.run(['as', '--32', *[f'--defsym={n}={v}' for n, v in ASM_SYMBOLS],
                        str(SOURCE / 'runtime.S'), '-o', str(d / 's.o')], check=True)
        (d / 'link.ld').write_text('SECTIONS { .text 0 : { *(.text*) *(.rodata*) } '
                                  '/DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) } }')
        subprocess.run(['ld', '-r', '-m', 'elf_i386', '-T', str(d / 'link.ld'),
                        '-o', str(d / 'runtime.o'), str(d / 'c.o'), str(d / 's.o')], check=True)
        data = (d / 'runtime.o').read_bytes()
    shoff = struct.unpack_from('<I', data, 32)[0]
    entsize, count, strings = struct.unpack_from('<3H', data, 46)
    sections = [struct.unpack_from('<10I', data, shoff + i * entsize) for i in range(count)]
    def content(s):
        return data[s[4]:s[4] + s[5]]
    def name(table, off):
        return table[off:table.index(0, off)].decode('ascii')
    names = content(sections[strings])
    by_name = {name(names, s[0]): (i, s) for i, s in enumerate(sections)}
    for n in ('.data', '.bss'):
        if n in by_name and by_name[n][1][5]:
            raise ValueError('mutable runtime state is forbidden in executable allocations')
    text_index, text_section = by_name['.text']
    symtab = by_name['.symtab'][1]
    symnames = content(sections[symtab[6]])
    symbols, labels = [], {}
    for off in range(0, symtab[5], 16):
        n, value, _, _, _, section = struct.unpack_from('<IIIBBH', content(symtab), off)
        n = name(symnames, n)
        symbols.append((n, value, section))
        if section == text_index and n:
            labels[n] = value
    relocations = []
    for off, info in struct.iter_unpack('<II', content(by_name['.rel.text'][1])):
        n, value, section = symbols[info >> 8]
        if section == text_index:
            n = 'code'
        elif section not in (0, 0xFFF1):
            raise ValueError('unexpected relocation section')
        kind = info & 255
        if kind not in (1, 2):
            raise ValueError('unsupported relocation')
        relocations.append((off, kind, n, value))
    code = content(text_section)
    return code, relocations, labels


def generate():
    code, relocations, labels = _compile()
    capacity, capacity_relocations, capacity_labels = _compile(CAPACITY_DEFINES)
    lines = ['"""Generated by tools/roster_arena/build_runtime.py. EXPERIMENTAL / UNWITNESSED."""',
             '', 'CODE = bytes.fromhex(']
    lines += ['    "' + code[i:i + 40].hex() + '"' for i in range(0, len(code), 40)]
    lines += [')', 'RELOCATIONS = ('] + [f'    {r!r},' for r in relocations]
    lines += [')', 'LABELS = {'] + [f'    {n!r}: {v},' for n, v in sorted(labels.items())]
    lines += ['}', '', 'CAPACITY_CODE = bytes.fromhex(']
    lines += ['    "' + capacity[i:i + 40].hex() + '"' for i in range(0, len(capacity), 40)]
    lines += [')', 'CAPACITY_RELOCATIONS = ('] + [f'    {r!r},' for r in capacity_relocations]
    lines += [')', 'CAPACITY_LABELS = {'] + [f'    {n!r}: {v},' for n, v in sorted(capacity_labels.items())]
    return '\n'.join(lines + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if TARGET.read_text() != result:
            raise SystemExit('arena runtime differs; rebuild it')
    else:
        TARGET.write_text(result)
    print('Arena runtime verified' if args.check else 'Arena runtime generated')
