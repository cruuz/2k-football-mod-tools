#!/usr/bin/env python3
"""b81-retail-free-art (fix 1, the reviewer's injections): the key-path allowlist of every shipped data document that
holds operations, written into packaging/check_2k5_mod_studio_release.py (DOCUMENT_SHAPES) by this tool, never by hand.

A document's shape is the set of its key paths: ``a.b`` for a dict key, ``[]`` for a list item, ``{kind}`` after an
operation (a dict with a string ``op``; ``{rule:module}`` for a rule), and ``*`` for the keys of a dict keyed by data
(donor ids, chunk numbers, team codes: VARIABLE below). The release check refuses a document whose shape has a path its
schema's list does not hold: an unknown operation, an unknown key at any depth.
  python3 tools/b81_uniforms/gate_shapes.py [--check]"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("release_check", ROOT / "packaging/check_2k5_mod_studio_release.py")
release = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(release)
START = "DOCUMENT_SHAPES = {   # generated by tools/b81_uniforms/gate_shapes.py: do not edit by hand\n"
END = "}   # end of DOCUMENT_SHAPES\n"


def documents():
    out = {}
    for path in sorted((ROOT / "data").rglob("*.json")):
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError):
            continue
        if isinstance(document, dict) and release._holds_operations(document):
            out[path.relative_to(ROOT).as_posix()] = document
    return out


def build():
    shapes = {}
    for relative, document in documents().items():
        schema = document.get("schema")
        if not isinstance(schema, str):
            raise SystemExit(f"{relative}: an operation document without a schema")
        shapes.setdefault(schema, set()).update(release._shape(document))
    return {schema: sorted(paths) for schema, paths in sorted(shapes.items())}


def render(shapes):
    lines = [START]
    for schema, paths in shapes.items():
        lines.append(f"    {schema!r}: frozenset((\n")
        for path in paths:
            lines.append(f"        {path!r},\n")
        lines.append("    )),\n")
    lines.append(END)
    return "".join(lines)


def main():
    text = (ROOT / "packaging/check_2k5_mod_studio_release.py").read_text(encoding="utf-8")
    i, j = text.index(START), text.index(END) + len(END)
    new = text[:i] + render(build()) + text[j:]
    if "--check" in sys.argv:
        if new != text:
            print("DOCUMENT_SHAPES_STALE", file=sys.stderr)
            return 1
        print("DOCUMENT_SHAPES current")
        return 0
    (ROOT / "packaging/check_2k5_mod_studio_release.py").write_text(new, encoding="utf-8")
    print(json.dumps({schema: len(paths) for schema, paths in build().items()}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
