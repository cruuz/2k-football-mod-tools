"""Regenerate the signed-franchise ownership routines using the Studio's freestanding i386 compiler."""
from pathlib import Path
import argparse
import sys

SOURCE = Path(__file__).resolve().parent
ROOT = SOURCE.parents[1]
sys.path.insert(0, str(ROOT))
from tools.nfl2k5_injured_reserve_build import generate

TARGET = ROOT / 'mod_editor/core/nfl2k5_franchise_ownership_code.py'
ENTRIES = ('ownership_trade_stub', 'ownership_release_stub', 'ownership_contract_stub',
           'ownership_repair_loaded', 'ownership_store')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(SOURCE, entries=ENTRIES, heading='Generated by tools/franchise_ownership/build.py with GCC 13.3 and GNU binutils 2.42.')
    if args.check:
        if TARGET.read_text() != text:
            raise SystemExit('The signed-franchise ownership runtime is stale.')
    else:
        TARGET.write_text(text, newline='\n')
