#!/usr/bin/env python3
"""hu1 repair for the pinned v0.6.1 image (alone or after the hd1 repair): the N27 scorebar corner and
Washington's menu helmets.

The rounded upper-right corner changes two fixed-size textures of the sprite scorebug's appended
resources in gamedata.iff: the score_buga atlas and Washington's home panel sb29h0. Both are
regenerated by the Studio's own compiler from this tree. The 2026 helmet W changes eight fixed-size
menu slots in the outer archive (the Team Select helmet cards at 256 and 128, the two uniform cards
and the two schedule miniatures), each painted by the Studio module nfl2k5_menu_helmet_w2026 to its
pin. Bytes are written only where they differ, inside those spans. --prove reads the disc and applies the writes to a memory overlay, without
a disc copy. --apply writes to an explicitly supplied copy. Both modes refuse unknown hashes, scan
the whole image and emit scope, Studio equality and zero-write replay receipts.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT), str(ROOT/'tools')]
from mod_editor.core import nfl2k5_scorebug_ingame as scene
from mod_editor.core import nfl2k5_scorebug_resources as art
from mod_editor.core import nfl2k5_scorebug_sprite as sprite
from mod_editor.core import platform_compat as io
from nfl_outer import HEADER_SIZE

PINS = Path(__file__).with_name('hu1_repair_pins.json')
BLOCK = 4 << 20


def sha(data):
    return hashlib.sha256(data).hexdigest()


def require(ok, message):
    if not ok:
        raise ValueError(message)


class Image:
    """Positional reads of the disc, optionally through an overlay of pending writes."""
    def __init__(self, fd, size, writes=()):
        self.fd, self.size, self.writes = fd, size, list(writes)

    def read(self, count, offset):
        block = bytearray(io.pread(self.fd, count, offset))
        require(len(block) == count, 'short image read')
        for off, _old, new in self.writes:
            lo, hi = max(offset, off), min(offset+count, off+len(new))
            if lo < hi:
                block[lo-offset:hi-offset] = new[lo-off:hi-off]
        return bytes(block)


def locate(image, pins):
    """Absolute offset of the scorebug appendix and a pack view that resolves the HUD outer through the pack table."""
    entries, _ = scene.layout.xc.parse_xdvdfs(image.fd, image.size)
    pack = entries[pins['pack_entry']]
    count = struct.unpack('<I', image.read(4, pack.byte_offset))[0]
    require(art.HUD_OUTER_INDEX < count, 'unknown pack 0 table')
    at = pack.byte_offset+HEADER_SIZE+art.HUD_OUTER_INDEX*12
    name_id, size, sector = struct.unpack('<3I', image.read(12, at))
    require(name_id == pins['outer_name_id'] and size >= art.HUD_SIZE+pins['appendix_size'], 'unknown HUD outer')
    outer = pack.byte_offset+sector*2048

    def read(n, offset):
        require(offset >= art.HUD_START, 'Sprite sources lie inside the HUD outer.')
        return image.read(n, outer+offset-art.HUD_START)
    return outer+art.HUD_SIZE, art.PackView(art.HUD_START+size, read)


def studio(view):
    data, receipt = sprite.appendix(view, None, True, 'auto')
    offsets, at = {}, 0
    for row in receipt['components']:
        offsets[row['name']] = (at, row['size'])
        at += row['size']
    return data, offsets


def menu(image, path):
    """Washington's menu helmet slots: disc ranges found through the outer archive, bytes read and painted through
    the overlay so a replay sees pending writes."""
    from mod_editor.core import nfl2k5_menu_helmet_w2026 as helmets
    from tools.nfl2k5_playbook_position_recode import OuterImage
    doc = helmets.spec()
    writes, spans = [], []
    with OuterImage(path) as archive:
        for target in doc['targets']:
            at, raw = helmets.locate(archive, target['aggregate'], target['member'])
            ranges = [(pack.image_offset+offset, length) for pack, offset, length in archive._segments(at, len(raw))]
            before = b''.join(image.read(n, o) for o, n in ranges)
            digest = sha(before)
            label = 'TXTR menu %s/%s' % (target['aggregate'], target['member'])
            require(digest in (target['before_sha256'], target['after_sha256']), 'unknown span bytes: '+label)
            after = before if digest == target['after_sha256'] else helmets.paint(before, doc['model'], target)[0]
            require(sha(after) == target['after_sha256'], 'Studio output pin differs: '+label)
            inner = 0
            for o, n in ranges:
                spans.append((o, n, label))
                writes += differences(before[inner:inner+n], after[inner:inner+n], o)
                inner += n
    return writes, spans


def plan(image, pins, path=None):
    start, view = locate(image, pins)
    require(start == pins['appendix_offset'], 'appendix moved')
    data, offsets = studio(view)
    require(len(data) == pins['appendix_size'], 'Studio appendix size changed')
    writes, spans = [], []
    for row in pins['spans']:
        off, size = offsets[row['name']]
        require((off, size) == (row['appendix_offset'], row['size']), 'Studio component moved: '+row['name'])
        after = data[off:off+size]
        require(sha(after) == row['after_sha256'], 'Studio output pin differs: '+row['name'])
        before = image.read(size, start+off)
        require(sha(before) in (row['before_sha256'], row['after_sha256']), 'unknown span bytes: '+row['name'])
        spans.append((start+off, size, row['kind']+' '+row['name']))
        writes += differences(before, after, start+off)
    if path is not None:
        menu_writes, menu_spans = menu(image, path)
        writes += menu_writes
        spans += menu_spans
    return writes, spans, start, data, offsets


def differences(before, after, base):
    """Minimal fixed writes; unchanged bytes are never submitted to pwrite."""
    start = None
    for i in range(len(before)+1):
        different = i < len(before) and before[i] != after[i]
        if different and start is None:
            start = i
        if not different and start is not None:
            yield (base+start, before[start:i], after[start:i])
            start = None


def scan(image, spans=()):
    """SHA-256 of every byte through the overlay, and how many bytes differ from the disc inside and outside spans."""
    allowed = sorted(spans)
    digest = hashlib.sha256()
    changed = outside = 0
    for pos in range(0, image.size, BLOCK):
        n = min(BLOCK, image.size-pos)
        raw = io.pread(image.fd, n, pos)
        block = image.read(n, pos)
        digest.update(block)
        if block != raw:
            for i, (a, b) in enumerate(zip(raw, block)):
                if a != b:
                    changed += 1
                    outside += not any(o <= pos+i < o+s for o, s, _ in allowed)
    return digest.hexdigest(), changed, outside


def appendix_report(image, start, data, offsets):
    have = image.read(len(data), start)
    return {name: sum(a != b for a, b in zip(have[o:o+s], data[o:o+s]))
            for name, (o, s) in offsets.items() if have[o:o+s] != data[o:o+s]}


def run(path, receipt_path, apply=False):
    pins = json.loads(PINS.read_text(encoding='utf-8'))
    flags = (os.O_RDWR if apply else os.O_RDONLY) | getattr(os, 'O_BINARY', 0)
    fd = os.open(path, flags)
    try:
        size = os.fstat(fd).st_size
        require(size == pins['disc_size'], 'unknown disc size')
        disc = Image(fd, size)
        before, _, _ = scan(disc)
        outputs = {row['after']: name for name, row in pins['inputs'].items()}
        require(before in pins['inputs'] or before in outputs, 'unknown disc hash; no writes made')
        if before in outputs:
            writes, spans, start, data, offsets = plan(disc, pins, path)
            require(not writes, 'a repaired image needs writes')
            receipt = dict(mode='disc' if apply else 'memory_overlay', input=pins['inputs'][outputs[before]]['label']+' (already repaired)',
                           written_bytes=0, replay_changed_bytes=0, before_sha256=before, after_sha256=before,
                           studio_appendix_mismatch_bytes=appendix_report(disc, start, data, offsets))
        else:
            expected = pins['inputs'][before]['after']
            writes, spans, start, data, offsets = plan(disc, pins, path)
            overlay = Image(fd, size, writes)
            projected, changed, outside = scan(overlay, spans)
            require(outside == 0, 'bytes changed outside declared spans')
            require(changed == sum(len(n) for _, _, n in writes), 'write scope mismatch')
            require(projected == expected, 'projected disc hash differs')
            replay, *_ = plan(overlay, pins, path)
            require(not replay, 'replay changed bytes')
            receipt = dict(mode='disc' if apply else 'memory_overlay', input=pins['inputs'][before]['label'],
                           disc_size=size, before_sha256=before, after_sha256=projected,
                           written_bytes=changed, bytes_outside_spans=outside, full_image_scan=True,
                           replay_changed_bytes=0, studio_spans_equal=True, menu_helmet_spans=sum(1 for *_, k in spans if k.startswith('TXTR menu')),
                           studio_appendix_mismatch_bytes_after=appendix_report(overlay, start, data, offsets),
                           declared_spans=[dict(offset=o, size=s, purpose=k) for o, s, k in spans],
                           writes=[dict(offset=o, size=len(n), before_sha256=sha(b), after_sha256=sha(n)) for o, b, n in writes])
            if apply:
                for off, old, _new in writes:
                    require(io.pread(fd, len(old), off) == old, 'input changed after preflight')
                for off, _old, new in writes:
                    require(io.pwrite(fd, new, off) == len(new), 'short write')
                os.fsync(fd)
                require(scan(disc)[0] == projected, 'disc read-back failed')
                restored = Image(fd, size, [(o, n, b) for o, b, n in writes])
                require(scan(restored)[0] == before, 'outside-span full-disc hash differs')
                replay, *_ = plan(disc, pins, path)
                require(not replay, 'replay on disc changed bytes')
            else:
                receipt['physical_disc_written_bytes'] = 0
        Path(receipt_path).write_text(json.dumps(receipt, indent=2)+'\n', encoding='utf-8', newline='\n')
        print(json.dumps({k: receipt[k] for k in ('mode', 'input', 'written_bytes', 'replay_changed_bytes', 'after_sha256')}))
        if 'bytes_outside_spans' in receipt:
            print('FULL IMAGE SCOPE: changed', receipt['written_bytes'], 'outside declared spans', receipt['bytes_outside_spans'])
            print('STUDIO EQUALITY: score_buga, sb29h0 and the eight Washington menu helmets PASS; whole appendix'
                  ' mismatch after:', receipt['studio_appendix_mismatch_bytes_after'] or 'none')
    finally:
        os.close(fd)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('disc', type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--prove', action='store_true')
    mode.add_argument('--apply', action='store_true', help='write only to your authorized disc copy')
    parser.add_argument('--receipt', required=True, type=Path)
    args = parser.parse_args()
    run(args.disc, args.receipt, args.apply)


if __name__ == '__main__':
    main()
