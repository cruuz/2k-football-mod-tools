#!/usr/bin/env python3
"""Rebuild the in-place history-pool runtime (job b780 hist1) with GNU binutils; development use only.

The generated ``mod_editor/core/nfl2k5_history_pool_code.py`` is checked in, so Studio users never need an assembler.
Every site is linked at its own retail address (tools/nfl2k5_history_pool/link.ld), so the template has no relocations.
``--check`` fails if the checked-in template differs from a fresh build (binutils 2.42). The retail bytes of each site
are read from the pinned USA default.xbe (NFL2K5_RETAIL_XBE, or the default extraction path).
"""
from __future__ import annotations

from pathlib import Path
import argparse
import hashlib
import os
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(__file__).resolve().parent / "nfl2k5_history_pool"
TARGET = ROOT / "mod_editor/core/nfl2k5_history_pool_code.py"
RETAIL_XBE = Path(os.environ.get("NFL2K5_RETAIL_XBE",
                                 "/media/noah/Storage/for codex 1.0/extracted/ESPN NFL 2K5 (USA)/default.xbe"))
SITES = (".site_a", ".site_b", ".site_c", ".site_d", ".site_e", ".site_f")


def _sections(elf: bytes) -> dict[str, tuple[int, bytes]]:
    if elf[:6] != b"\x7fELF\x01\x01":
        raise ValueError("expected little-endian ELF32")
    shoff = struct.unpack_from("<I", elf, 32)[0]
    entsize, count, strings = struct.unpack_from("<3H", elf, 46)
    rows = [struct.unpack_from("<10I", elf, shoff + i * entsize) for i in range(count)]
    names = elf[rows[strings][4]:rows[strings][4] + rows[strings][5]]
    out = {}
    for r in rows:
        name = names[r[0]:names.index(0, r[0])].decode("ascii")
        out[name] = (r[3], elf[r[4]:r[4] + r[5]])         # (address, bytes)
    return out


def generate(source: Path = SOURCE) -> str:
    sys.path.insert(0, str(ROOT))
    from mod_editor.core.nfl2k5_cave_oracle import RETAIL_SHA256, XbeImage
    retail = RETAIL_XBE.read_bytes()
    if hashlib.sha256(retail).hexdigest() != RETAIL_SHA256:
        raise SystemExit("the retail default.xbe pin differs")
    image = XbeImage(retail)
    with tempfile.TemporaryDirectory(prefix="nfl2k5-history-pool-") as folder:
        d = Path(folder)
        subprocess.run(["as", "--32", "-o", str(d / "r.o"), str(source / "runtime.S")], check=True)
        subprocess.run(["ld", "-m", "elf_i386", "-T", str(source / "link.ld"), "-o", str(d / "r.elf"), str(d / "r.o")],
                       check=True)
        found = _sections((d / "r.elf").read_bytes())
    lines = ['"""Generated by tools/nfl2k5_history_pool_build.py (binutils 2.42). Each site: (label, VA, retail bytes,',
             'patched bytes), linked at its own address (no relocations)."""', "", "SITES = ("]
    for name in SITES:
        va, code = found[name]
        before = image.read(va, len(code))
        lines.append(f"    ({name[1:]!r}, 0x{va:08X},")
        for blob, close in ((before, "),"), (code, ")),")):
            lines.append("     bytes.fromhex(")
            lines += ['         "' + blob[i:i + 48].hex() + '"' for i in range(0, len(blob), 48)]
            lines.append("     " + close)
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != result:
            raise SystemExit("history pool runtime template is stale")
        print("history pool runtime template verified")
    else:
        TARGET.write_text(result, encoding="utf-8", newline="\n")
        print("history pool runtime template generated")


if __name__ == "__main__":
    main()
