        self.assertEqual(by["fg_dispatch"][3][0], 0xE8)
        self.assertEqual(by["fg_commit"][3][0], 0xE8)
        for name in ("fourth", "play", "target", "two_point"):
            self.assertEqual(by[name][3][0], 0xE9)
        replay, receipt = patch.apply(out, level="modern2")
        self.assertIs(replay, out)
        self.assertEqual(receipt["changed_bytes"], 0)

