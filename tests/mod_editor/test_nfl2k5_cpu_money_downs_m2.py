    def test_overtime_examples(self):
        away_both = dict(level="modern2", quarter=5, seconds=400, quarter_seconds=300, ot_bits=3, home=False)
        # behind by 7 on the last possession: never punt, never kick
        for own, dist in ((40, 2), (45, 1), (60, 8), (85, 3), (30, 15)):
            self.assertEqual(patch.decision(own_yard=own, distance=dist, score_margin=-7, **away_both), "go")
            self.assertEqual(patch.decision(own_yard=own, distance=dist, score_margin=-4, native_fg=True, **away_both), "go")
        # behind by a field goal: a native kick stays, anything else goes (never a punt)
        self.assertEqual(patch.decision(own_yard=40, distance=8, score_margin=-3, native_fg=False, **away_both), "go")
        self.assertEqual(patch.decision(own_yard=75, distance=3, score_margin=-3, native_fg=True, **away_both), "retail")
        # sudden death (tied after both possessions) and leading keep the retail logic
        self.assertEqual(patch.decision(own_yard=40, distance=2, score_margin=0, **away_both), "retail")
        self.assertEqual(patch.decision(own_yard=40, distance=2, score_margin=3, **away_both), "retail")
        # first possession: the typical table without clock or score terms
        first = dict(away_both, ot_bits=2)
        self.assertEqual(patch.decision(own_yard=50, distance=6, score_margin=0, **first), "go")
        self.assertEqual(patch.decision(own_yard=50, distance=8, score_margin=0, **first), "retail")
        # the home team reads bit 0 as its own and bit 1 as the opponent's
        self.assertEqual(patch.decision(own_yard=50, distance=6, score_margin=0, **dict(first, home=True)), "retail")
        self.assertEqual(patch.decision(own_yard=50, distance=6, score_margin=0, **dict(first, home=True, ot_bits=1)), "go")
        # no possession tracking (retail sudden death, an era profile): retail
        self.assertEqual(patch.decision(own_yard=40, distance=2, score_margin=-7, **dict(away_both, ot_bits=0)), "retail")
        self.assertEqual(patch.decision(own_yard=40, distance=2, score_margin=-7, **dict(away_both, ot_bits=1)), "retail")

    def test_two_point_chart_examples(self):
        def c(margin, quarter, seconds, **kw):
            return patch.two_point_decision(margin=margin, quarter=quarter, seconds=seconds, quarter_seconds=900, **kw)
        for quarter, seconds in ((1, 800), (2, 100), (3, 500), (4, 700), (4, 5)):
            self.assertTrue(c(-2, quarter, seconds))                 # retail already goes at -2 at any time: kept
            for kick in (-3, 0, 6, 7):
                self.assertFalse(c(kick, quarter, seconds), (kick, quarter, seconds))
        # only the final 20 seconds when one point down after the touchdown
        self.assertTrue(c(-1, 4, 20))
        self.assertFalse(c(-1, 4, 21))
        # down 8 before a touchdown that leaves -2 is handled above; the ESPN readings by margin (game seconds, 15 minute quarters)
        self.assertTrue(c(-8, 3, 450))         # 450 + 900 = 1350 s left: midway through the third quarter or later
        self.assertFalse(c(-8, 3, 460))
        self.assertFalse(c(-8, 2, 100))        # 100 + 900 + 900 = 1900 s left
        self.assertTrue(c(-10, 4, 300))
        self.assertFalse(c(-10, 4, 600))       # eight to nine minutes
        self.assertTrue(c(-5, 3, 600))
        self.assertFalse(c(-5, 1, 400))        # first half
        self.assertTrue(c(1, 3, 600))
        self.assertFalse(c(1, 1, 400))
        self.assertTrue(c(5, 4, 100))
        self.assertFalse(c(5, 2, 400))
        self.assertTrue(c(4, 4, 250))
        self.assertFalse(c(4, 4, 400))
        self.assertTrue(c(12, 4, 500))
        self.assertFalse(c(12, 3, 400))
        # overtime: -2 as retail; -1 only on the last possession (both possession bits); never after the first touchdown (+6)
        self.assertTrue(c(-2, 5, 300))
        self.assertTrue(c(-1, 5, 300, ot_bits=3))
        self.assertFalse(c(-1, 5, 300, ot_bits=2))
        self.assertFalse(c(-1, 5, 300))
        self.assertFalse(c(6, 5, 300, ot_bits=2))
        self.assertFalse(c(6, 5, 300, ot_bits=3))
        self.assertFalse(c(-1, 0, 300))
        self.assertFalse(c(17, 4, 100))
        self.assertFalse(c(-17, 4, 100))

