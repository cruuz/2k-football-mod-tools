        self.assertEqual(base.read(0x20AC4D, 2), b"\x6a\x03")
        self.assertEqual(image.read(0x20AA1E, 2), b"\x6a\x02")
        self.assertEqual(image.read(0x20AC4D, 2), b"\x6a\x02")
