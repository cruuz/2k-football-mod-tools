"""The ESPN scorebug's inputs come from the user's disc, and produce the same bytes.

Nothing the scorebug needs ships: the retail scene, its span and the three P8 atlases are
retail bytes, and our repaints of those atlases are derived from them.  They are read out of
the user's own image at build time and the art is regenerated by the shipped generator.  The
tests that matter here are therefore:

* availability is about this BUILD, not about files on the maintainer's disk;
* with the developer asset folder hidden and no extracted pack archive in sight, every
  replacement span is byte-for-byte the one the developer route produces;
* the full step over a real copy of the disc leaves the same resource bytes behind.

The last two are gated on the retail extraction and image; every other test runs anywhere.
"""

