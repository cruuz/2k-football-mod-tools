class SwapPlayerDialog(QDialog):
    """Pick the rostered player to exchange slots with: a team, then one of its players."""

    def __init__(self, panel: "RosterEditorPanel", player: rr.Player, parent: QWidget | None = None) -> None:
        super().__init__(parent or panel)
        self.setWindowTitle(f"Swap {player.display} with…")
        self._panel = panel
        self._player = player
        self._players: list[rr.Player] = []
        layout = QVBoxLayout(self)
        row = QHBoxLayout()
        row.addWidget(QLabel("Team"))
        self.team_combo = QComboBox()
        self.team_combo.setAccessibleName("Swap team")
        assert panel.document is not None
        for team in panel.document.teams:
            self.team_combo.addItem(f"{team.abbreviation} · {team.display} ({len(team.slots)})", team.index)
        self.team_combo.currentIndexChanged.connect(self._fill)
        row.addWidget(self.team_combo, 1)
        layout.addLayout(row)
        self.player_list = QListWidget()
        self.player_list.setAccessibleName("Swap player")
        layout.addWidget(self.player_list, 1)
        buttons = QDialogButtonBox(QDialogButtonBox.Ok | QDialogButtonBox.Cancel)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)
        other = next((t for t in player.teams if t != panel.document.team_of(player)), None)
        default = other if other is not None else (0 if panel.document.team_of(player) != 0 else 1)
        self.team_combo.setCurrentIndex(default)
        self._fill(default)

    def _fill(self, _index: int) -> None:
        assert self._panel.document is not None
        team_index = int(self.team_combo.currentData())
        self._players = [p for p in self._panel.document.team_players(team_index) if p is not self._player]
        self.player_list.clear()
        for candidate in self._players:
            record = candidate.record
            self.player_list.addItem(f"{record.position_name} #{record.values['jersey']} {candidate.display}")
        if self._players:
            self.player_list.setCurrentRow(0)

    def select_player(self, other: rr.Player) -> bool:
        for row, candidate in enumerate(self._players):
            if candidate is other:
                self.player_list.setCurrentRow(row)
                return True
        return False

    def chosen(self) -> rr.Player | None:
        row = self.player_list.currentRow()
        return self._players[row] if 0 <= row < len(self._players) else None


