        table = QTableWidget(0, len(self.COLUMNS))
        table.setHorizontalHeaderLabels(list(self.COLUMNS))
        table.setAccessibleName(accessible_name)
        table.setEditTriggers(QAbstractItemView.NoEditTriggers)
