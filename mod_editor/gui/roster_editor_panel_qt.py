# --------------------------------------------------------------------------------------------- undo
@dataclass
class UndoEntry:
    label: str
    undo: Callable[[], None]
    redo: Callable[[], None]


class UndoStack:
    """A plain command stack.  Every edit on this page is reversible and says what it was."""

    def __init__(self, limit: int = 500, on_change: Callable[[], None] | None = None) -> None:
        self._done: list[UndoEntry] = []
        self._undone: list[UndoEntry] = []
        self._limit = limit
        self.on_change = on_change

    def push(self, entry: UndoEntry) -> None:
        self._done.append(entry)
        del self._done[: max(0, len(self._done) - self._limit)]
        self._undone.clear()
        if self.on_change is not None:
            self.on_change()

    def can_undo(self) -> bool:
        return bool(self._done)

    def can_redo(self) -> bool:
        return bool(self._undone)

    def undo(self) -> str:
        if not self._done:
            return ""
        entry = self._done.pop()
        entry.undo()
        self._undone.append(entry)
        return entry.label

    def redo(self) -> str:
        if not self._undone:
            return ""
        entry = self._undone.pop()
        entry.redo()
        self._done.append(entry)
        return entry.label

    def clear(self) -> None:
        self._done.clear()
        self._undone.clear()

    @property
    def depth(self) -> tuple[int, int]:
        return len(self._done), len(self._undone)


