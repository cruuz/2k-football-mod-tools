# --------------------------------------------------------------------------------------------- undo
@dataclass
class UndoEntry:
    label: str
    undo: Callable[[], None]
    redo: Callable[[], None]


class UndoStack:
    """A plain command stack.  Every edit on this page is reversible and says what it was."""

    def __init__(self, limit: int = 500, on_change: Callable[[], None] | None = None) -> None:
        self._done: list[UndoEntry] = []
        self._undone: list[UndoEntry] = []
        self._limit = limit
        self.on_change = on_change
        # b780-uxfix: only goes up (push, undo, redo, clear). len(_done) stops at the 500-entry limit, so an export
        # snapshot taken there kept matching while the user went on editing, and later edits closed without a prompt.
        self.revision = 0

    def _changed(self) -> None:
        self.revision += 1
        if self.on_change is not None:
            self.on_change()

    def push(self, entry: UndoEntry) -> None:
        self._done.append(entry)
        del self._done[: max(0, len(self._done) - self._limit)]
        self._undone.clear()
        self._changed()

    def can_undo(self) -> bool:
        return bool(self._done)

    def can_redo(self) -> bool:
        return bool(self._undone)

    def undo(self) -> str:
        if not self._done:
            return ""
        entry = self._done[-1]
        entry.undo()
        self._done.pop()
        self._undone.append(entry)
        self._changed()   # b780-uxfix: the title's * follows Undo
        return entry.label

    def redo(self) -> str:
        if not self._undone:
            return ""
        entry = self._undone[-1]
        entry.redo()
        self._undone.pop()
        self._done.append(entry)
        self._changed()   # b780-uxfix: the title's * follows Redo
        return entry.label

    def clear(self) -> None:
        """A reset (a new roster loads): the revision moves on; the owner refreshes once its load is complete."""
        self._done.clear()
        self._undone.clear()
        self.revision += 1

    @property
    def depth(self) -> tuple[int, int]:
        return len(self._done), len(self._undone)


def run_in_background(parent: QWidget | None, title: str, text: str, work: Callable[[], Any]) -> Any:
    """Run ``work()`` on a worker thread while a busy dialog keeps the window painting.

    Returns what ``work`` returns, or raises what it raised, on the calling thread. The call
    blocks the way a modal dialog does (nothing else in the Studio can be clicked), but the
    event loop keeps running, so the window never goes "Not Responding" during a long CSV preview.
    """

    outcome: dict[str, Any] = {}

    def target() -> None:
        try:
            outcome["value"] = work()
        except Exception as exc:  # noqa: BLE001 - handed back to the caller's thread below
            outcome["error"] = exc

    progress = QProgressDialog(text, "", 0, 0, parent)
    progress.setWindowTitle(title)
    progress.setCancelButton(None)
    progress.setWindowModality(Qt.WindowModal)
    progress.setMinimumDuration(0)
    progress.setAutoClose(False)
    progress.setAutoReset(False)
    progress.show()
    worker = threading.Thread(target=target, name="roster-csv-preview", daemon=True)
    worker.start()
    try:
        while worker.is_alive():
            QApplication.processEvents()
            worker.join(0.03)
    finally:
        worker.join()
        progress.close()
        progress.deleteLater()
    if "error" in outcome:
        raise outcome["error"]
    return outcome.get("value")


class PlayerCsvPreviewDialog(QDialog):
    """Read-only full diff, including every refused row, before one import command."""

    def __init__(self, preview: rr.CsvPreview, parent=None, repreview=None):
        super().__init__(parent)
        self.setWindowTitle("Preview player CSV import")
        self.resize(950, 620)
        self._repreview = repreview
        self.preview = preview
        layout = QVBoxLayout(self)
        self.summary = QLabel()
        self.summary.setWordWrap(True)
        layout.addWidget(self.summary)
        self.appearance_checkbox = None
        receipt = preview.receipt
        if receipt.get('format') == rr.NFL2K5TOOL_CSV and repreview is not None:
            self.appearance_checkbox = QCheckBox("Also import appearance and bio columns")
            self.appearance_checkbox.setToolTip(
                "Imports the tool's position, jersey number, college, DOB, ids, body and equipment "
                "columns too. Leave this off for a community ratings file.")
            self.appearance_checkbox.setChecked(not receipt.get('rating_only', True))
            self.appearance_checkbox.toggled.connect(self._toggle_appearance)
            layout.addWidget(self.appearance_checkbox)
        self.table = QTableWidget(0, 6)
        self.table.setHorizontalHeaderLabels(("CSV row", "Player / pool + index", "Field", "Before", "After", "Refusal"))
        self.table.setEditTriggers(QAbstractItemView.NoEditTriggers)
        self.table.setAccessibleName("Player CSV changes and refused rows")
        layout.addWidget(self.table)
        help_text = QLabel(rr.CSV_HELP)
        help_text.setWordWrap(True)
        layout.addWidget(help_text)
        self.buttons = QDialogButtonBox(QDialogButtonBox.Apply | QDialogButtonBox.Cancel)
        self.apply_button = self.buttons.button(QDialogButtonBox.Apply)
        self.apply_button.setText("Apply valid rows")
        self.apply_button.clicked.connect(self.accept)
        self.buttons.rejected.connect(self.reject)
        layout.addWidget(self.buttons)
        self._fill(preview)

    def _fill(self, preview: rr.CsvPreview) -> None:
        self.preview = preview
        receipt = preview.receipt
        ignored = receipt.get('ignored_columns') or []
        summary = (f"{receipt['changed']} players, {receipt['fields']} fields change; "
                   f"{len(receipt['refused'])} rows refused.")
        if ignored:
            summary += (f" {len(ignored)} non-rating columns were ignored (position, jersey, "
                        "appearance, equipment and bio)")
            summary += ("; tick the box to import them."
                        if self.appearance_checkbox is not None else ".")
        skipped = receipt.get('skipped') or []
        if skipped:
            summary += (f" {len(skipped)} appearance or bio values this roster cannot take were skipped; "
                        "the rest of those rows still imports (listed below).")
        summary += (" Apply changes to the loaded roster, then use Undo to reverse the whole import.")
        self.summary.setText(summary)
        entries = []
        for row in receipt['changes']:
            identity = row.get('label') or f"{row['pool']}:{row['index']}"
            for field in row['changes']:
                entries.append((row['row'], identity, field['field'],
                                field['before'], field['after'], ""))
        for row in receipt['refused']:
            identity = row.get('label') or f"{row['pool']}:{row['index']}"
            entries.append((row['row'], identity, "", "", "", row['reason']))
        for row in skipped:
            identity = row.get('label') or f"{row['pool']}:{row['index']}"
            entries.append((row['row'], identity, row['field'], "", "",
                            "Skipped, rest of the row imported: " + row['reason']))
        self.table.setRowCount(len(entries))
        for i, row in enumerate(entries):
            for j, value in enumerate(row):
                self.table.setItem(i, j, QTableWidgetItem(str(value)))
        self.table.resizeColumnsToContents()
        self.apply_button.setEnabled(preview.before != preview.after)

    def _toggle_appearance(self, checked: bool) -> None:
        try:
            preview = run_in_background(
                self, "Previewing the CSV",
                "Checking every row against the roster again. This can take a little while on a big file.",
                lambda: self._repreview(bool(checked)))
        except Exception as exc:  # noqa: BLE001 - a slot must never raise into Qt
            # b779 rv1: the box and the preview must agree, because Apply uses the preview. The old
            # preview is still the one shown, so put the box back to match it and say what failed.
            with QSignalBlocker(self.appearance_checkbox):
                self.appearance_checkbox.setChecked(not checked)
            QMessageBox.warning(self, "Could not preview the CSV again",
                                f"{exc}\nThe box was put back to match the preview shown. "
                                "Correct the CSV and preview it again.")
            return
        self._fill(preview)


