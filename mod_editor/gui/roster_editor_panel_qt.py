    def paste_player(self, mode: str = "all") -> int:
        player = self.selected_player()
        if player is None or self._clipboard is None:
            return 0
        before = player.record.copy()
        count = rr.copy_player(self._clipboard, player.record, mode=mode)
        if not count:
            return 0

