    def load_disc(self, path: Path | str) -> bool:
        try:
            document = rr.load_image(path)
        except Exception as exc:  # noqa: BLE001 - one message for the status line
            self._set_status(f"Could not read the roster: {plain_error(exc)}")
            return False
        state = "retail" if rr.resource_status(
            document.resource_header + bytes(document.body)) == "retail" else "already edited"
        # a disc can say which position scheme it is on: mod_build.inspect reads the EDGE rename and
        # the one-pool position_pools patch straight off its executable
        self.load_document(document, label=f"{Path(path).name} ({state})", source=Path(path),
                           kind="disc", detection=self.detect_scheme(document, Path(path)))
        return True

    def load_save(self, path: Path | str) -> bool:
        try:
            container = rr.SaveContainer.load(path)
        except Exception as exc:  # noqa: BLE001
            self._set_status(f"Could not read the save: {plain_error(exc)}")
            return False
        try:
            document = container.document()
        except Exception as exc:  # noqa: BLE001
            # the signature verified: keep the container so Check my rosters… can still scan it read-only
            self._college_check_container = (Path(path), container)
            self._set_status(f"Could not read the save: {plain_error(exc)} "
                             "(Check my rosters… on the Checks tab can still list its college references, read-only)")
            return False
        # a save carries no executable, so the scheme can only come from the records
        self.load_document(document, label=f"{Path(path).name} (signature verified)",
                           source=Path(path), kind="save", detection=self.detect_scheme(document))
        self._show_franchise(self._franchise_summary(container.savegame))
        self.franchise_panel.load(container, document)
        # b81 R5: a roster save's coaches are edited on the Coaches page beside Roster; the build staff plan (also
        # called Coaches) is for discs, so it steps aside instead of showing a second, disabled Coaches tab
        self.pages.setTabVisible(self._coaches_index, not self.franchise_panel.coaches_only)
        return True

    @staticmethod
    def _franchise_summary(savegame: bytes) -> dict[str, Any] | None:
        """The season summary of a franchise save, or None for a roster save (never raises)."""

        try:
            from mod_editor.core import nfl2k5_franchise_save as fs
            if not fs.is_franchise_save(savegame):
                return None
            save = fs.FranchiseSave(savegame)
            summary = save.summary()
            users = summary["user_teams"]
            coach = save.coach_for_team(users[0]) if users else None
            summary["coach"] = (f"{coach.name} ({coach.fields['wins']}-{coach.fields['losses']}-"
                                f"{coach.fields['ties']})" if coach else "")
            return summary
        except Exception:  # noqa: BLE001 - the card is a convenience, loading must not depend on it
            return None

