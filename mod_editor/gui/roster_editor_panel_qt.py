    def edits_key(self) -> tuple[frozenset[tuple[str, int]], int]:
        """What an export or a written copy is compared with: the edited players and the undo stack's revision."""
        return frozenset(self._dirty), self.undo_stack.revision

    def write_copy_to(self, target: Path | str, *, overwrite: bool = False) -> dict[str, Any]:
        """Disc: copy the image and apply.  Save: write a re-signed container.  Never the source.

        b780-uxfix: a written copy holds the edits, so they count as saved (the title's * goes, closing stops asking).
        """
        result = self._write_copy_target(target, overwrite=overwrite)
        self._edits_snapshot = self.edits_key()
        if self.undo_stack.on_change is not None:
            self.undo_stack.on_change()
        return result

    def _write_copy_target(self, target: Path | str, *, overwrite: bool = False) -> dict[str, Any]:

        if self.document is None:
            raise rr.RosterRecordError("no roster is loaded")
        self.document.check_depth_locks()
        destination = Path(target)
        if self._source_kind == "save":
            if self.franchise_panel.active:          # roster edits first, then the franchise edits, one copy
                return self.franchise_panel.write_copy_to(destination, overwrite=overwrite)
            return rr.save_document(self.document, destination, overwrite=overwrite)
        if self._source_path is None:
            raise rr.RosterRecordError("this roster did not come from a disc or a save")
        if destination.resolve() == self._source_path.resolve():
            raise rr.RosterRecordError("the target must not be the source disc")
        if self._source_path.is_dir():
            raise rr.RosterRecordError(
                "this roster was read from a loose pack folder, which has no image to copy. "
                "Use Save roster edits… and apply them from Build & Share, or load a disc image.")
        if destination.exists() and not overwrite:
            raise rr.RosterRecordError(f"{destination} exists")
        edits = self.edits_document()
        return self._write_disc_copy(self._source_path, destination, edits, overwrite)

    @staticmethod
    def _write_disc_copy(source: Path, destination: Path, edits: dict[str, Any], overwrite: bool) -> dict[str, Any]:
        from mod_editor.core.image_use import studio_staging
        from mod_editor.core.platform_compat import publish_no_replace
        with studio_staging(destination.parent, ".roster-") as stage:
            staged = stage.path / destination.name
            shutil.copyfile(source, staged)
            result = rr.apply(staged, edits)
            if overwrite:
                os.replace(staged, destination)
            else:
                publish_no_replace(staged, destination)
        return result

