"""Moment face scans: a retired player's own retail face for the Anniversary moments and the classic teams.
EXPERIMENTAL / UNWITNESSED.

Job fs1 (Noah, 2026-10-18, watching the b775 test disc): "Eli Manning MVP. We should use Eli's actual face scan if we
still have it, for any player that actually has their face scan in the game."

How a head is chosen (PROVED OFFLINE, reports/assets/nfl2k5_live_face_texture_compatibility.json): the roster record's
+0x06 word is both the live-head id (``f####`` face, ``h####`` alternate face, ``n####`` neck and skull in
``pf####.iff``, ``s####`` head shape in ``pf####.iff`` and in the FaceShapes table) and the post-play portrait id
(``portrait:####``). A missing id falls back to the generic head for the record's skin and face bits. The lookup is by
number, so any number of records, in any number of roster files, may point at one id: Tom Brady's retail id 2712 is
already shared by seven moment files.

The catch: the SOFTDRINK 2026 league wrote new faces into 193 retail ids (every id a retired 2004 player held that no
current record used). Eli Manning's retail id 6504 now holds D.J. Reed. Pointing the 2008 Giants at 6504 would show
Reed, so the 2004 scan has to live in another id. This option copies it there:

- the target is a retail id that no record of the finished main roster uses and whose retail owner no moment or
  classic player needs (``data/nfl2k5_moment_scans.json`` lists every pair; the table is generated by
  tools/b77/fs1_scans_plan.py and checked here against the build's own main roster);
- ``f`` (raw DXT1) and the portrait (raw P8) are copied with the resource name rewritten to the new id (the name is
  the only id-dependent field; the 160 header bytes of 60 faces and 40 portraits were compared);
- ``h`` and ``n`` (VC-LZ) are decoded, renamed and re-encoded with the encoder that reproduces the retail streams
  byte for byte, into the target's fixed stored allocation (the same fixed-span rebuild the 2026 faces use). A pair
  is only listed when the renamed stream fits;
- the head shape ``s`` (both copies) is copied only when the two spans have the same size (mode ``copied``);
  otherwise the target keeps its own shape (mode ``kept``), as every 2026 face already does.

Nothing is allocated, no archive entry grows, no retail byte is shipped: the source is the user's own retail game.
The roster side (which id each player gets) lives in nfl2k5_espn25_more_moments.compile_team and
nfl2k5_espn25_rosters.compile_resource.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data/nfl2k5_moment_scans.json"
SCHEMA = "nfl2k5_moment_scans/v1"
OWNER = "nfl2k5_moment_scans"
REQUESTS = ()
EVIDENCE = "EXPERIMENTAL / UNWITNESSED"
UI_LABEL = "Anniversary and classic teams: retail face scans"
HELP_TEXT = (
    "EXPERIMENTAL / UNWITNESSED. With the Anniversary moments or the classic teams on, players who had a face scan "
    "in the retail game keep it even when the 2026 roster reused their retail head: the retail head, neck and "
    "portrait are copied into an unused head id and the moment rosters point there. Needs the retail game.")
SHAPE_MODES = ("copied", "kept")
NOPHOTO_BASE = 7100               # retail's no-photo range: no portrait, no live face, the generic head by skin
# The only fields a relocated resource changes: its own name, then (h, n) the compressed stream that holds it.
NAME_AT = 64                      # resource name, UTF-16LE, in the 32 byte wrapper + 32 byte name offset (f, s, portrait)


class MomentScansError(ValueError):
    pass


def require(ok, message):
    if not ok:
        raise MomentScansError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------------------------------------------------- the data

def load(path=DATA):
    """[{name, retail, slot, shape}] sorted by retail id; every field validated, no catalog needed."""
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    require(isinstance(doc, dict) and doc.get("schema") == SCHEMA and isinstance(doc.get("scans"), list),
            "moment scans data: foreign schema")
    scans = doc["scans"]
    for row in scans:
        require(isinstance(row, dict) and set(row) == {"name", "retail", "slot", "shape"}, "moment scans row fields")
        require(isinstance(row["name"], str) and row["name"].strip(), "moment scans row name")
        require(type(row["retail"]) is int and type(row["slot"]) is int
                and 0 < row["retail"] < 10000 and 0 < row["slot"] < 10000, "moment scans ids are 1..9999")
        require(row["shape"] in SHAPE_MODES, f"{row['name']}: shape mode")
    require(len({r["retail"] for r in scans}) == len(scans), "moment scans: a retail id appears twice")
    require(len({r["slot"] for r in scans}) == len(scans), "moment scans: a target id appears twice")
    require(not ({r["slot"] for r in scans} & {r["retail"] for r in scans}), "moment scans: a target id is also a source")
    require([r["retail"] for r in scans] == sorted(r["retail"] for r in scans), "moment scans must be sorted by retail id")
    return [dict(r) for r in scans]


def slots(scans=None):
    """{retail face id: the id its scan lives in}."""
    return {r["retail"]: r["slot"] for r in (load() if scans is None else scans)}


def retail_ids(scans=None):
    return frozenset(r["retail"] for r in (load() if scans is None else scans))


# ----------------------------------------------------------------------------------------------- native spans (offline)

def _tools():
    from . import nfl2k5_roster_records as rr
    rr._outer_image()                      # puts tools/ on sys.path
    import nfl_txtr
    return nfl_txtr


def _catalog():
    from . import nfl2k5_roster_appearance_transfer as at
    return at._catalog()


def families(row):
    """Selector families copied for one pair: f h n, the shape pair when copied, and the portrait."""
    out = ["f", "h", "n"]
    if row["shape"] == "copied":
        out += ["s", "s_global"]
    return out


def selector(face_id, family):
    return f"portrait:{face_id:04d}" if family == "portrait" else f"{face_id:04d}:{family}"


def _patch_name(raw, old, new):
    """The span with its UTF-16LE resource name replaced (same length, exactly one occurrence at NAME_AT)."""
    a, b = old.encode("utf-16-le"), new.encode("utf-16-le")
    require(len(a) == len(b) and raw[NAME_AT:NAME_AT + len(a)] == a, f"resource {old!r} does not carry its name at 0x{NAME_AT:x}")
    require(raw.count(a) == 1, f"resource {old!r} name occurs more than once")
    return raw[:NAME_AT] + b + raw[NAME_AT + len(b):]


def relocated_span(catalog, family, face_id, slot, source_raw, target_raw):
    """The bytes the target slot must hold: the source resource renamed to the target id.

    source_raw / target_raw are the full spans (catalog span_size) read from the retail game and the build copy.
    """
    t = _tools()
    from . import nfl2k5_roster_appearance_transfer as at
    src_row = catalog[selector(face_id, family)]
    dst_row = catalog[selector(slot, family)]
    require(len(source_raw) == src_row["span_size"] and len(target_raw) == dst_row["span_size"], f"{family}: span size")
    if family in ("f", "portrait"):
        old = src_row.get("resource_name") or src_row["name"]
        new = dst_row.get("resource_name") or dst_row["name"]
        out = _patch_name(source_raw, old, new)
    elif family in ("s", "s_global"):
        require(len(source_raw) == len(target_raw), f"{family}: shapes of different sizes cannot be copied")
        out = _patch_name(source_raw, src_row["resource_name"], dst_row["resource_name"])
    else:
        # h, n: VC-LZ. Decode the retail stream, rename inside the payload, encode into the target's fixed allocation.
        chunk = t.Chunk(0, 0, "TXTR", *t.HEADER.unpack_from(source_raw)[1:])
        decoded, info = t.decode_chunk(source_raw, chunk)
        require(info is not None, f"{family}: the retail resource is not compressed")
        name_at = src_row["name_offset"]
        old, new = src_row["resource_name"].encode("utf-16-le"), dst_row["resource_name"].encode("utf-16-le")
        require(decoded[name_at:name_at + len(old)] == old and decoded.count(old) == 1, f"{family}: payload name")
        patched = decoded[:name_at] + new + decoded[name_at + len(old):]
        try:
            out, _info = t.rebuild_compressed_chunk_fixed_span(target_raw, patched)
        except t.TxtrError as exc:
            raise MomentScansError(f"{dst_row['resource_name']}: {exc}") from exc
    at._check_span(selector(slot, family), out, dst_row)
    return out


# ----------------------------------------------------------------------------------------------------- the disc image

def _read(archive, shapes, catalog, face_id, family):
    from . import nfl2k5_roster_appearance_transfer as at
    sel = selector(face_id, family)
    require(sel in catalog, f"{sel} is not in the face catalog")
    row = catalog[sel]
    offset = at._entry_for(archive, row, shapes)
    return offset, archive.read(offset, row["span_size"]), row


def _pair_families(catalog, row):
    """Families to copy for one pair: f h n, the shape pair when copied, and the portrait (both ids must have one,
    so a stale post-play portrait of the target's former owner can never stay)."""
    require(selector(row["retail"], "portrait") in catalog and selector(row["slot"], "portrait") in catalog,
            f"{row['name']}: the retail game has no portrait for {row['retail']:04d} or {row['slot']:04d}")
    return families(row) + ["portrait"]


def _main_photos(path):
    from . import nfl2k5_roster_records as rr
    return frozenset(p.record.values["photo_id"] for p in rr.load_image(path).players)


def active_pairs(scans, catalog, src, s_shapes, dst, d_shapes, photos):
    """The pairs this build needs: those whose target id no main-roster record uses. A pair whose target id IS used
    (a stock retail roster: the retired players still hold their ids) is skipped, which is only sound while the retail
    head of its source id is intact on the target; the roster side then points at the retail id itself."""
    out = []
    for row in scans:
        if row["slot"] not in photos:
            out.append(row)
            continue
        _, a, _ = _read(src, s_shapes, catalog, row["retail"], "f")
        _, b, _ = _read(dst, d_shapes, catalog, row["retail"], "f")
        require(a == b, f"{row['name']}: the main roster uses head id {row['slot']:04d} and his retail head "
                        f"{row['retail']:04d} was overwritten, so his scan has nowhere to go")
    return out


def plan(source, target, scans=None, catalog=None, photos=None):
    """Read-only: [(selector, offset, expected bytes, current bytes)] for every span the active pairs change.

    source: the user's retail game (disc image or folder); target: the build copy (opened read-only here).
    photos: the target's main-roster photo ids (read from the target when None; an empty set plans every pair).
    """
    from . import nfl2k5_roster_records as rr
    from . import nfl2k5_roster_appearance_transfer as at
    scans = load() if scans is None else scans
    catalog = _catalog() if catalog is None else catalog
    photos = _main_photos(target) if photos is None else photos
    writes = []
    with rr._outer_image()(source) as src, rr._outer_image()(target) as dst:
        s_shapes, d_shapes = at._shape_offsets(src), at._shape_offsets(dst)
        for row in active_pairs(scans, catalog, src, s_shapes, dst, d_shapes, photos):
            for family in _pair_families(catalog, row):
                _, source_raw, srow = _read(src, s_shapes, catalog, row["retail"], family)
                # The source must be the stock retail resource (pinned by the shipped catalog).
                if family != "s_global":
                    require(sha(source_raw) == srow["span_sha256"], f"{selector(row['retail'], family)}: not the retail game")
                at._check_span(selector(row["retail"], family), source_raw, srow)
                offset, current, drow = _read(dst, d_shapes, catalog, row["slot"], family)
                expected = relocated_span(catalog, family, row["retail"], row["slot"], source_raw, current)
                writes.append((selector(row["slot"], family), offset, expected, current))
    return writes


def image_status(path, source, scans=None):
    """'retail' (every active target span still the stock retail bytes), 'applied' (every active span equals the
    expected copy; also when no pair is active), else 'foreign' (a mix, a changed or missing id, or a source that is
    not the retail game)."""
    from . import nfl2k5_roster_records as rr
    from . import nfl2k5_roster_appearance_transfer as at
    try:
        scans = load() if scans is None else scans
        catalog = _catalog()
        photos = _main_photos(path)
        states = set()
        with rr._outer_image()(source) as src, rr._outer_image()(path) as dst:
            s_shapes, d_shapes = at._shape_offsets(src), at._shape_offsets(dst)
            for row in active_pairs(scans, catalog, src, s_shapes, dst, d_shapes, photos):
                for family in _pair_families(catalog, row):
                    _, source_raw, srow = _read(src, s_shapes, catalog, row["retail"], family)
                    require(family == "s_global" or sha(source_raw) == srow["span_sha256"], "source is not the retail game")
                    _, current, drow = _read(dst, d_shapes, catalog, row["slot"], family)
                    # The retail bytes of the target id are in the source game too.
                    _, target_retail, _ = _read(src, s_shapes, catalog, row["slot"], family)
                    expected = relocated_span(catalog, family, row["retail"], row["slot"], source_raw, target_retail)
                    states.add("applied" if current == expected else "retail" if current == target_retail else "foreign")
        if not states:
            return "applied"
        return states.pop() if len(states) == 1 else "foreign"
    except (MomentScansError, ValueError, KeyError, IndexError, OSError, struct.error):
        return "foreign"


def check_roster(main_photos, scans=None):
    """Refuse a build whose finished main roster uses a target id of a pair that is needed (the id is its retail
    owner's retail head: nothing to copy over)."""
    scans = load() if scans is None else scans
    clash = sorted(r["slot"] for r in scans if r["slot"] in main_photos)
    require(not clash, "the main roster uses face ids reserved for the moment scans: " + ", ".join(f"{c:04d}" for c in clash))


def apply_to_image(path, source, scans=None):
    """Copy the scans into their unused ids on the build copy ``path`` (never on a user's original)."""
    from . import nfl2k5_roster_records as rr
    scans = load() if scans is None else scans
    state = image_status(path, source, scans)
    if state == "applied":
        return dict(status="already_applied", scans=len(scans))
    require(state == "retail", f"moment scans: the target ids are {state}")
    writes = plan(source, path, scans)
    receipts = []
    with rr._outer_image()(path, writable=True) as archive:
        for sel, offset, expected, current in writes:
            require(archive.write(offset, expected) == len(expected), f"{sel}: short write")
            require(archive.read(offset, len(expected)) == expected, f"{sel}: read-back differs")
            receipts.append({"selector": sel, "offset": offset, "size": len(expected),
                             "before_sha256": sha(current), "after_sha256": sha(expected)})
    require(image_status(path, source, scans) == "applied", "moment scans: read-back failed")
    return dict(status="applied", experimental=True, runtime_witnessed=False, scans=len(scans),
                pairs_copied=len({w[0].split(":")[-1 if w[0].startswith("portrait") else 0] for w in writes}),
                spans=receipts)
